import { entityDomain } from './capabilities';
import { normalizeHome } from './normalize';
import type { HassEntity, HausAccessory, Snapshot } from './types';

type Card = Record<string, unknown>;
const heading = (text: string): Card => ({
  type: 'heading',
  heading: text,
  heading_style: 'title',
});
const tile = (accessory: HausAccessory): Card => ({
  type: 'tile',
  entity: accessory.primaryEntityId,
  name: accessory.name,
  tap_action: { action: 'more-info' },
});
const grid = (cards: Card[]): Card => ({ type: 'grid', cards });
const camera = (entity: HassEntity): Card => ({
  type: 'picture-entity',
  entity: entity.entity_id,
  camera_view: 'auto',
  show_name: true,
  show_state: false,
});

/** A portable Lovelace config composed entirely from built-in cards. It never saves to HA. */
export function generateDashboard(snapshot: Snapshot): Record<string, unknown> {
  const model = normalizeHome(snapshot);
  const primary = model.accessories.filter(
    (accessory) => entityDomain(accessory.state) !== 'camera',
  );
  const sceneCards: Card[] = model.scenes.map((scene) => ({
    type: 'button',
    entity: scene.entity_id,
    name: scene.attributes.friendly_name,
    tap_action: {
      action: 'perform-action',
      perform_action: 'scene.turn_on',
      target: { entity_id: scene.entity_id },
    },
  }));
  const roomSections = model.rooms
    .filter((room) =>
      room.accessories.some((accessory) => entityDomain(accessory.state) !== 'camera'),
    )
    .map((room) =>
      grid([
        heading(room.name),
        ...room.accessories
          .filter((accessory) => entityDomain(accessory.state) !== 'camera')
          .map(tile),
      ]),
    );
  const registry = new Map(snapshot.entities.map((entry) => [entry.entity_id, entry]));
  const eligible = snapshot.states.filter(
    (entity) =>
      !registry.get(entity.entity_id)?.disabled_by && !registry.get(entity.entity_id)?.hidden_by,
  );
  const batteries = eligible.filter((entity) => entity.attributes.device_class === 'battery');
  const config = eligible.filter(
    (entity) => registry.get(entity.entity_id)?.entity_category === 'config',
  );
  return {
    title: `${snapshot.config.location_name} · Haus`,
    views: [
      {
        title: 'Home',
        path: 'home',
        icon: 'mdi:home-outline',
        type: 'sections',
        max_columns: 3,
        sections: [
          ...(sceneCards.length ? [grid([heading('Scenes'), ...sceneCards])] : []),
          ...(model.cameras.length
            ? [grid([heading('Cameras'), ...model.cameras.map(camera)])]
            : []),
          ...roomSections,
        ],
      },
      ...model.rooms.map((room) => ({
        title: room.name,
        path: `room-${room.id}`,
        icon: 'mdi:floor-plan',
        type: 'sections',
        max_columns: 3,
        sections: [
          grid([
            heading(room.name),
            ...room.accessories.map((accessory) =>
              entityDomain(accessory.state) === 'camera'
                ? camera(accessory.state)
                : tile(accessory),
            ),
          ]),
        ],
      })),
      {
        title: 'Batteries',
        path: 'batteries',
        icon: 'mdi:battery-outline',
        type: 'sections',
        sections: [
          grid([
            heading('Battery levels'),
            ...(batteries.length
              ? [
                  {
                    type: 'entities',
                    entities: batteries.map((entity) => entity.entity_id),
                    show_header_toggle: false,
                  },
                ]
              : [{ type: 'markdown', content: 'No battery entities are available.' }]),
          ]),
        ],
      },
      {
        title: 'Configuration',
        path: 'configuration',
        icon: 'mdi:cog-outline',
        type: 'sections',
        sections: [
          grid([
            heading('Home configuration'),
            {
              type: 'markdown',
              content: `Generated by Haus for **${snapshot.config.location_name}**.\n\n${model.rooms.length} rooms · ${primary.length} accessories · ${model.scenes.length} scenes.\n\nThis dashboard uses only built-in Home Assistant cards. Review the configuration before saving it in Home Assistant.`,
            },
            ...(config.length
              ? [
                  {
                    type: 'entities',
                    title: 'Device settings',
                    entities: config.map((entity) => entity.entity_id),
                    show_header_toggle: false,
                  },
                ]
              : []),
          ]),
        ],
      },
    ],
  };
}
