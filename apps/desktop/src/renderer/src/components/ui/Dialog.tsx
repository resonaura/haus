import type { ReactNode } from 'react';
import { HausDialog } from '@haus/ui';

export function Dialog({
  title,
  onClose,
  children,
  className = '',
}: {
  title: string;
  onClose: () => void;
  children: ReactNode;
  className?: string;
}) {
  return (
    <HausDialog title={title} onClose={onClose} className={className} backdrop="blur" scrollable>
      {children}
    </HausDialog>
  );
}
